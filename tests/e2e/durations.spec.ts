import { test, expect, type Page } from '@playwright/test';
import { writeFileSync } from 'node:fs';
import { doActivity, shownItem } from './helpers';
import { SESSIONS } from '../../src/content/sessions';

/**
 * Measured walk-through for session durations (docs/durations.md). Runs only with MEASURE=1 against a local build:
 *   npm run build && MEASURE=1 npx playwright test durations
 * For every session, in order, it counts the words actually rendered in the learn stage (lesson text, example,
 * activity, practice), the activity choices the learner must make, and the questions and their words, then writes
 * src/content/durations.ts. Rebuild after measuring. The bot's own clock time is recorded but not used: a script
 * is not a person.
 */
const words = (t: string) => t.split(/\s+/).filter(w => /[A-Za-z0-9]/.test(w)).length;
test.skip(!process.env.MEASURE, 'measurement run only');
test.setTimeout(900000);
async function quizMeasure(page: Page) {
  let n = 0, w = 0;
  for (;;) {
    const label = (await page.locator('section[aria-label] > p.muted').first().textContent())!.trim();
    const it = (await shownItem(page))!;
    w += words(it.q + ' ' + it.options.join(' ')); n++;
    await page.getByRole('radio', { name: it.options[it.answer], exact: true }).click();
    w += words(it.why);
    const last = /question (\d+) of \1$/.test(label);
    await page.getByRole('button', { name: /^(Next question|Finish)$/ }).click();
    if (last) return { n, w };
  }
}
test('measure every session', async ({ page }) => {
  const out: Record<string, unknown> = {};
  await page.goto('./');
  for (const s of SESSIONS) {
    const t0 = Date.now();
    await page.goto(`./#/session/${s.id}`);
    const art = page.locator('article');
    await expect(art.locator('h1')).toBeVisible();
    const learnText = await art.locator('.block').evaluateAll(els => els.map(e => (e as HTMLElement).innerText).join(' '));
    const interactions = await art.locator('section.activity').evaluateAll(els => els.length ? (els[0].querySelectorAll('fieldset').length || els[0].querySelectorAll('select').length || els[0].querySelectorAll('li').length || 1) : 0);
    await doActivity(page);
    await page.getByRole('button', { name: 'Next: explain it back' }).click();
    const explainWords = words(await page.locator('section[aria-label="Explain it back"]').innerText());
    await page.getByRole('button', { name: 'Skip for now' }).click();
    const q = await quizMeasure(page);
    const resultWords = words(await page.locator('section.result').innerText());
    out[s.id] = { words: words(learnText) + explainWords + resultWords, interactions, quizItems: q.n, quizWords: q.w, explain: true, botSeconds: Math.round((Date.now() - t0) / 100) / 10 };
    const save = page.getByRole('button', { name: /^(Save and continue|Continue without retaking)$/ });
    await save.click();
  }
  const data = { generatedAt: new Date().toISOString(), viewport: '412x915 Pixel 7 emulation', sessions: out };
  writeFileSync('src/content/durations.ts', '// Generated by tests/e2e/durations.spec.ts (MEASURE=1). Do not edit by hand. Method: docs/durations.md\n'
    + 'export const MEASURED: { generatedAt?: string; viewport?: string; sessions: Record<string, { words: number; interactions: number; quizItems: number; quizWords: number; explain: boolean; botSeconds?: number }> } = '
    + JSON.stringify(data, null, 1) + ';\n');
});
